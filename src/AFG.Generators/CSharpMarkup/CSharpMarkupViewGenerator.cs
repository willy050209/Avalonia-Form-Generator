using System.Globalization;

namespace AFG.Generators.CSharpMarkup;

/// <summary>
/// 將 UI AST 中介語意模型遞迴轉譯為純 C# Declarative Markup View 程式碼的生成器。
/// </summary>
public sealed class CSharpMarkupViewGenerator : ICodeGenerator
{
    public GeneratedSourceFile Generate(FormDocument document)
    {
        ArgumentNullException.ThrowIfNull(document);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.ComponentModel;");
        sb.AppendLine("using Avalonia;");
        sb.AppendLine("using Avalonia.Controls;");
        sb.AppendLine("using Avalonia.Data;");
        sb.AppendLine("using Avalonia.Layout;");
        sb.AppendLine("using Avalonia.Media;");
        sb.AppendLine("using Avalonia.Threading;");
        sb.AppendLine();
        sb.AppendLine($"namespace {document.RootNamespace};");
        sb.AppendLine();
        sb.AppendLine($"public partial class {document.ViewClassName} : UserControl");
        sb.AppendLine("{");
        sb.AppendLine($"    public {document.ViewClassName}()");
        sb.AppendLine("    {");
        sb.AppendLine("        InitializeComponent();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private void InitializeComponent()");
        sb.AppendLine("    {");

        // 遞迴生成根節點
        var rootCode = GenerateNodeCode(document.RootNode, indentLevel: 2, document.ViewModelClassName, document.UseCompiledBindings);
        sb.AppendLine($"        Content = {rootCode};");

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return new GeneratedSourceFile(
            FileName: $"{document.ViewClassName}.cs",
            Content: sb.ToString(),
            FileType: SourceFileType.View);
    }

    /// <summary>
    /// 遞迴將 AST 節點轉換為 C# Fluent 鏈式調用語法。
    /// </summary>
    public static string GenerateNodeCode(AstNode node, int indentLevel, string viewModelClassName, bool useCompiledBindings = false)
    {
        ArgumentNullException.ThrowIfNull(node);

        var indent = new string(' ', indentLevel * 4);
        var innerIndent = new string(' ', (indentLevel + 1) * 4);
        var sb = new StringBuilder();

        sb.AppendLine($"new {node.Type}()");

        // 1. 幾何與佈局屬性
        if (node.Width.HasValue)
        {
            sb.AppendLine($"{innerIndent}.Width({node.Width.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (node.Height.HasValue)
        {
            sb.AppendLine($"{innerIndent}.Height({node.Height.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (node.MinWidth.HasValue)
        {
            sb.AppendLine($"{innerIndent}.MinWidth({node.MinWidth.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (node.MinHeight.HasValue)
        {
            sb.AppendLine($"{innerIndent}.MinHeight({node.MinHeight.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (node.MaxWidth.HasValue)
        {
            sb.AppendLine($"{innerIndent}.MaxWidth({node.MaxWidth.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (node.MaxHeight.HasValue)
        {
            sb.AppendLine($"{innerIndent}.MaxHeight({node.MaxHeight.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (node.Margin != ThicknessModel.Zero)
        {
            sb.AppendLine($"{innerIndent}.Margin(new Thickness({FormatThickness(node.Margin)}))");
        }

        if (node.Padding != ThicknessModel.Zero)
        {
            sb.AppendLine($"{innerIndent}.Padding(new Thickness({FormatThickness(node.Padding)}))");
        }

        if (node.HorizontalAlignment != HorizontalAlignment.Stretch)
        {
            sb.AppendLine($"{innerIndent}.HorizontalAlignment(HorizontalAlignment.{node.HorizontalAlignment})");
        }

        if (node.VerticalAlignment != VerticalAlignment.Stretch)
        {
            sb.AppendLine($"{innerIndent}.VerticalAlignment(VerticalAlignment.{node.VerticalAlignment})");
        }

        if (node.Opacity < 1.0)
        {
            sb.AppendLine($"{innerIndent}.Opacity({node.Opacity.ToString(CultureInfo.InvariantCulture)})");
        }

        if (!node.IsEnabled)
        {
            sb.AppendLine($"{innerIndent}.IsEnabled(false)");
        }

        if (!node.IsVisible)
        {
            sb.AppendLine($"{innerIndent}.IsVisible(false)");
        }

        if (node.ZIndex != 0)
        {
            sb.AppendLine($"{innerIndent}.ZIndex({node.ZIndex})");
        }

        // 2. 容器附屬屬性 (Attached Properties)
        if (node.CanvasLeft.HasValue)
        {
            sb.AppendLine($"{innerIndent}.CanvasLeft({node.CanvasLeft.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (node.CanvasTop.HasValue)
        {
            sb.AppendLine($"{innerIndent}.CanvasTop({node.CanvasTop.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (node.GridRow != 0)
        {
            sb.AppendLine($"{innerIndent}.GridRow({node.GridRow})");
        }

        if (node.GridColumn != 0)
        {
            sb.AppendLine($"{innerIndent}.GridColumn({node.GridColumn})");
        }

        if (node.GridRowSpan > 1)
        {
            sb.AppendLine($"{innerIndent}.GridRowSpan({node.GridRowSpan})");
        }

        if (node.GridColumnSpan > 1)
        {
            sb.AppendLine($"{innerIndent}.GridColumnSpan({node.GridColumnSpan})");
        }

        if (node.Dock.HasValue)
        {
            sb.AppendLine($"{innerIndent}.Dock(Dock.{node.Dock.Value})");
        }

        // 3. 容器專屬設置
        if (node.RowDefinitions.Count > 0)
        {
            var rowDefs = string.Join(", ", node.RowDefinitions.Select(r => $"\"{r}\""));
            sb.AppendLine($"{innerIndent}.RowDefinitions({rowDefs})");
        }

        if (node.ColumnDefinitions.Count > 0)
        {
            var colDefs = string.Join(", ", node.ColumnDefinitions.Select(c => $"\"{c}\""));
            sb.AppendLine($"{innerIndent}.ColumnDefinitions({colDefs})");
        }

        if (node.Orientation.HasValue)
        {
            sb.AppendLine($"{innerIndent}.Orientation(Orientation.{node.Orientation.Value})");
        }

        // 4. 控制項專屬外觀與內容（依型別智慧判定 Content vs Text）
        if (IsContentControl(node.Type))
        {
            var textOrContent = !string.IsNullOrEmpty(node.Content) ? node.Content : node.Text;
            if (!string.IsNullOrEmpty(textOrContent))
            {
                sb.AppendLine($"{innerIndent}.Content(\"{EscapeString(textOrContent)}\")");
            }
        }
        else if (IsTextControl(node.Type))
        {
            var textOrContent = !string.IsNullOrEmpty(node.Text) ? node.Text : node.Content;
            if (!string.IsNullOrEmpty(textOrContent))
            {
                sb.AppendLine($"{innerIndent}.Text(\"{EscapeString(textOrContent)}\")");
            }
        }
        else
        {
            if (!string.IsNullOrEmpty(node.Content))
            {
                sb.AppendLine($"{innerIndent}.Content(\"{EscapeString(node.Content)}\")");
            }
            if (!string.IsNullOrEmpty(node.Text))
            {
                sb.AppendLine($"{innerIndent}.Text(\"{EscapeString(node.Text)}\")");
            }
        }

        if (!string.IsNullOrEmpty(node.Header))
        {
            sb.AppendLine($"{innerIndent}.Header(\"{EscapeString(node.Header)}\")");
        }

        if (!string.IsNullOrEmpty(node.Watermark))
        {
            sb.AppendLine($"{innerIndent}.Watermark(\"{EscapeString(node.Watermark)}\")");
        }

        if (node.IsChecked.HasValue)
        {
            sb.AppendLine($"{innerIndent}.IsChecked({(node.IsChecked.Value ? "true" : "false")})");
        }

        if (node.Value.HasValue)
        {
            sb.AppendLine($"{innerIndent}.Value({node.Value.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (node.FontSize.HasValue)
        {
            sb.AppendLine($"{innerIndent}.FontSize({node.FontSize.Value.ToString(CultureInfo.InvariantCulture)})");
        }

        if (!string.IsNullOrWhiteSpace(node.Background))
        {
            sb.AppendLine($"{innerIndent}.Background(Brush.Parse(\"{EscapeString(node.Background)}\"))");
        }

        if (!string.IsNullOrWhiteSpace(node.Foreground))
        {
            sb.AppendLine($"{innerIndent}.Foreground(Brush.Parse(\"{EscapeString(node.Foreground)}\"))");
        }

        // 5. MVVM 綁定配置
        foreach (var binding in node.Bindings)
        {
            var bindingCall = useCompiledBindings
                ? binding.Mode switch
                {
                    BindingMode.TwoWay => $".{binding.TargetProperty}(({viewModelClassName} vm) => vm.{binding.ViewModelProperty}, BindingMode.TwoWay)",
                    BindingMode.OneWay => $".{binding.TargetProperty}(({viewModelClassName} vm) => vm.{binding.ViewModelProperty}, BindingMode.OneWay)",
                    _ => $".{binding.TargetProperty}(({viewModelClassName} vm) => vm.{binding.ViewModelProperty})"
                }
                : binding.Mode switch
                {
                    BindingMode.TwoWay => $".{binding.TargetProperty}(nameof({viewModelClassName}.{binding.ViewModelProperty}), BindingMode.TwoWay)",
                    BindingMode.OneWay => $".{binding.TargetProperty}(nameof({viewModelClassName}.{binding.ViewModelProperty}), BindingMode.OneWay)",
                    _ => $".{binding.TargetProperty}(nameof({viewModelClassName}.{binding.ViewModelProperty}))"
                };

            sb.AppendLine($"{innerIndent}{bindingCall}");
        }

        // 6. 事件映射至命令
        foreach (var evt in node.Events)
        {
            var cmdCall = useCompiledBindings
                ? $".Command(({viewModelClassName} vm) => vm.{evt.CommandProperty})"
                : $".Command(nameof({viewModelClassName}.{evt.CommandProperty}))";

            sb.AppendLine($"{innerIndent}{cmdCall}");
        }

        // 7. 遞迴子節點 (Children - 僅包含實體可視控制項，不可視元件由 ViewModel / DI 管理)
        var visualChildren = node.Children
            .Where(c => !IsNonVisualComponent(c.Type))
            .ToList();

        if (visualChildren.Count > 0)
        {
            sb.AppendLine($"{innerIndent}.Children(");
            for (var i = 0; i < visualChildren.Count; i++)
            {
                var childCode = GenerateNodeCode(visualChildren[i], indentLevel + 2, viewModelClassName, useCompiledBindings);
                var isLast = i == visualChildren.Count - 1;
                var trailingComma = isLast ? string.Empty : ",";
                sb.AppendLine($"{new string(' ', (indentLevel + 2) * 4)}{childCode}{trailingComma}");
            }
            sb.Append($"{innerIndent})");
        }

        return sb.ToString().TrimEnd();
    }

    public static bool IsNonVisualComponent(ControlType type) => type switch
    {
        ControlType.DispatcherTimer or ControlType.BackgroundWorker or
        ControlType.BluetoothClient or ControlType.SerialPortService => true,
        _ => false
    };

    private static bool IsContentControl(ControlType type) => type switch
    {
        ControlType.Button or ControlType.CheckBox or ControlType.RadioButton or ControlType.Border => true,
        _ => false
    };

    private static bool IsTextControl(ControlType type) => type switch
    {
        ControlType.TextBlock or ControlType.TextBox => true,
        _ => false
    };

    private static string FormatThickness(ThicknessModel thickness) =>
        $"{thickness.Left.ToString(CultureInfo.InvariantCulture)}, {thickness.Top.ToString(CultureInfo.InvariantCulture)}, {thickness.Right.ToString(CultureInfo.InvariantCulture)}, {thickness.Bottom.ToString(CultureInfo.InvariantCulture)}";

    private static string EscapeString(string input) =>
        input.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);
}
